import { spawnSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const uiRoot = path.resolve(__dirname, "..")
const sourceRoot = path.join(uiRoot, "src")
const lucideRoot = path.resolve(uiRoot, "../../node_modules/lucide-solid/dist/source/icons")
const outputFile = path.join(sourceRoot, "styles/components/pixel-icons.css")
const magick = process.env.MAGICK_BIN || "magick"
const bitmapSize = 20

const walk = (directory) => fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
  const fullPath = path.join(directory, entry.name)
  return entry.isDirectory() ? walk(fullPath) : [fullPath]
})

const iconNames = new Set()
for (const file of walk(sourceRoot).filter((candidate) => candidate.endsWith(".tsx"))) {
  const source = fs.readFileSync(file, "utf8")
  for (const match of source.matchAll(/import\s*{([^}]*)}\s*from\s*["']lucide-solid["']/g)) {
    for (const specifier of match[1].split(",")) {
      const name = specifier.trim().split(/\s+as\s+/)[0]
      if (name) iconNames.add(name)
    }
  }
}

const className = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()
const sourceName = (name) => name
  .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
  .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
  .replace(/([A-Za-z])([0-9])/g, "$1-$2")
  .toLowerCase()

const escapeXml = (value) => String(value)
  .replaceAll("&", "&amp;")
  .replaceAll('"', "&quot;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")

const readIconNode = (name) => {
  const iconFile = path.join(lucideRoot, `${sourceName(name)}.jsx`)
  if (!fs.existsSync(iconFile)) throw new Error(`Lucide source missing for ${name}: ${iconFile}`)
  const source = fs.readFileSync(iconFile, "utf8")
  const match = source.match(/const iconNode = (\[[\s\S]*?\]);/)
  if (!match) throw new Error(`iconNode missing in ${iconFile}`)
  return Function(`"use strict"; return (${match[1]})`)()
}

const renderSourceSvg = (nodes) => {
  const body = nodes.map(([tag, attributes]) => {
    const attrs = Object.entries(attributes)
      .filter(([key]) => key !== "key")
      .map(([key, value]) => `${key}="${escapeXml(value)}"`)
      .join(" ")
    return `<${tag} ${attrs}/>`
  }).join("")
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2.75" stroke-linecap="square" stroke-linejoin="miter">${body}</svg>`
}

const rasterize = (svg, name) => {
  const result = spawnSync(magick, [
    "-background", "none", "svg:-", "-resize", `${bitmapSize}x${bitmapSize}!`, "-alpha", "extract",
    "-threshold", "22%", "-depth", "8", "gray:-",
  ], { input: svg, maxBuffer: 1024 * 1024 })
  if (result.status !== 0) {
    throw new Error(`ImageMagick failed for ${name}: ${result.stderr.toString("utf8")}`)
  }
  if (result.stdout.length !== bitmapSize * bitmapSize) {
    throw new Error(`Unexpected ${name} bitmap size: ${result.stdout.length}`)
  }
  return Array.from(result.stdout, (value) => value >= 128)
}

const bitmapMask = (pixels) => {
  const commands = []
  for (let y = 0; y < bitmapSize; y += 1) {
    let x = 0
    while (x < bitmapSize) {
      if (!pixels[y * bitmapSize + x]) {
        x += 1
        continue
      }
      const start = x
      while (x < bitmapSize && pixels[y * bitmapSize + x]) x += 1
      commands.push(`M${start} ${y}h${x - start}v1H${start}z`)
    }
  }
  if (commands.length === 0) throw new Error("Generated empty bitmap")
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${bitmapSize} ${bitmapSize}" shape-rendering="crispEdges"><path d="${commands.join("")}"/></svg>`
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`
}

const sortedNames = [...iconNames].sort((left, right) => left.localeCompare(right))
let css = `/* Auto-generated by scripts/build-pixel-icons.mjs. ${bitmapSize}x${bitmapSize}, 1-bit alpha. */\n\n`
css += `svg.lucide {\n  display: inline-block !important;\n  min-width: ${bitmapSize}px !important;\n  min-height: ${bitmapSize}px !important;\n  flex: 0 0 auto;\n  background-color: currentColor !important;\n  -webkit-mask-image: var(--pixel-icon-mask) !important;\n  mask-image: var(--pixel-icon-mask) !important;\n  -webkit-mask-position: center !important;\n  mask-position: center !important;\n  -webkit-mask-repeat: no-repeat !important;\n  mask-repeat: no-repeat !important;\n  -webkit-mask-size: 100% 100% !important;\n  mask-size: 100% 100% !important;\n  image-rendering: pixelated !important;\n  shape-rendering: crispEdges !important;\n  stroke: none !important;\n  fill: none !important;\n}\n\nsvg.lucide > * {\n  display: none !important;\n}\n\n`

for (const name of sortedNames) {
  const mask = bitmapMask(rasterize(renderSourceSvg(readIconNode(name)), name))
  css += `svg.lucide-${className(name)} {\n  --pixel-icon-mask: ${mask};\n}\n\n`
}

fs.writeFileSync(outputFile, css)
console.log(`Generated ${sortedNames.length} aliased pixel icons -> ${path.relative(uiRoot, outputFile)}`)
